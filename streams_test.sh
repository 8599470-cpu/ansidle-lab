#!/bin/bash

# 1. Використання стандартного введення (stdin)
echo "Введіть назву директорії, яку хочете перевірити:"
read dir_name

# 2. Спроба виконати команду та перенаправлення потоків
# stdout іде в /dev/null (ховаємо успіх), stderr іде в окремий файл
ls "$dir_name" > /dev/null 2> error.log

# 3. Обробка коду повернення (exit code)
if [ $? -eq 0 ]; then
    # Потік виводу (stdout)
    echo "Успіх: Директорія '$dir_name' існує."
else
    # Потік помилок (stderr)
    echo "Помилка: Директорії '$dir_name' не існує або доступ заборонено." >&2
    echo "Деталі помилки збережено в error.log:"
    cat error.log
fi

# Приклад примусового коду повернення
exit 0
